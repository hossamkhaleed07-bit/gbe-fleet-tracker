-- Just enough of the live Supabase database for the migrations under test to run in
-- PGlite: the roles, auth.uid()/auth.jwt() (read from request.jwt.claims, as on
-- Supabase), the private role helpers of 050/053/056, and fuel_invoice_records as it
-- stands after 044/046/048/053/055.

create role anon nologin;
create role authenticated nologin;

create schema auth;
create function auth.jwt() returns jsonb
language sql stable
as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create function auth.uid() returns uuid
language sql stable
as $$ select nullif(auth.jwt() ->> 'sub', '')::uuid $$;
grant usage on schema auth to anon, authenticated;
grant execute on all functions in schema auth to anon, authenticated;

create schema private;
grant usage on schema private to authenticated;
create function private.app_role() returns text
language sql stable
as $$ select coalesce((select auth.jwt()) -> 'app_metadata' ->> 'role', '') $$;
create function private.is_admin() returns boolean language sql stable as $$ select private.app_role() = 'admin' $$;
create function private.is_fleet_manager() returns boolean language sql stable as $$ select private.app_role() = 'fleet_manager' $$;
create function private.is_viewer() returns boolean language sql stable as $$ select private.app_role() = 'viewer' $$;
grant execute on function private.app_role(), private.is_admin(), private.is_fleet_manager(), private.is_viewer() to authenticated;

grant usage on schema public to anon, authenticated;

create table public.fuel_invoice_records (
  id uuid primary key default gen_random_uuid(),
  data_source text, invoice_number text, internal_number text, fuel_type text,
  cost numeric, amount numeric, vat numeric, user_name text, entry_date date, card_type text,
  status text, use_type text, branch text, nid text, da_name text, deduction_code text, remarks text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  created_by text, updated_by text, batch text, row_color text,
  sort_order bigint generated by default as identity
);

-- stands in for the live fuel_invoice_records_before_write trigger (not in the repo)
create function public.fuel_invoice_records_touch() returns trigger
language plpgsql
as $$ begin new.updated_at := now(); return new; end; $$;
create trigger fuel_invoice_records_before_write before insert or update on public.fuel_invoice_records
  for each row execute function public.fuel_invoice_records_touch();

alter table public.fuel_invoice_records enable row level security;
grant select, insert, update, delete on public.fuel_invoice_records to authenticated;
create policy "read"   on public.fuel_invoice_records for select to authenticated using (private.is_admin() or private.is_fleet_manager());
create policy "insert" on public.fuel_invoice_records for insert to authenticated with check (private.is_admin());
create policy "update" on public.fuel_invoice_records for update to authenticated using (private.is_admin()) with check (private.is_admin());
create policy "delete" on public.fuel_invoice_records for delete to authenticated using (private.is_admin());
